// ============================================================================
//  ui.h — мини-библиотека построения UI прямо во фреймбуфере RGB565
//  Проект: jd9165_hello_display (ESP32-P4, экран 1024x600, JD9165)
// ----------------------------------------------------------------------------
//  Назначение: показать, как построить UI для экрана 1024x600 БЕЗ LVGL:
//    1) геометрия — прямоугольники (панели, кнопки, полосы прогресса);
//    2) текст — готовые шрифты DejaVu Sans (кириллица!), конвертированные
//       в C-массивы скриптом tools/make_font.py;
//    3) компоновка — экран собирается из панелей фиксированной сеткой;
//    4) динамика — "тиком" (ui_demo_tick) перерисовываются только
//       изменившиеся области, а не весь экран.
//
//  Почему готовые шрифты DejaVu Sans:
//    - свободная лицензия (Bitstream Vera + public domain дополнения),
//      допускает встраивание в прошивку и распространение;
//    - есть полная кириллица, цифры, знаки « » — № ° × · и т.д.;
//    - это те же шрифты, что стоят в Linux/Ubuntu — знакомый вид.
// ============================================================================

#ifndef UI_H
#define UI_H

#include <stdint.h>
#include <stddef.h>

// ----------------------------------------------------------------------------
// Геометрия экрана (должна совпадать с LCD_H_RES / LCD_V_RES в main.c)
// ----------------------------------------------------------------------------
#define UI_H_RES    1024
#define UI_V_RES    600

// ----------------------------------------------------------------------------
// Цвета RGB565: 5 бит красного | 6 бит зелёного | 5 бит синего
// UI_RGB565(r,g,b) — перевод 0..255 компонент в формат пикселя RGB565
// ----------------------------------------------------------------------------
#define UI_RGB565(r, g, b) \
    (uint16_t)( (((r) & 0xF8) << 8) | (((g) & 0xFC) << 3) | (((b) & 0xF8) >> 3) )

// Палитра тёмной темы (подобрана для IPS-матрицы 1024x600)
#define UI_COL_BG          UI_RGB565(0x0F, 0x12, 0x18)   // фон экрана
#define UI_COL_PANEL       UI_RGB565(0x1A, 0x21, 0x30)   // фон панели
#define UI_COL_PANEL_HI    UI_RGB565(0x23, 0x2E, 0x44)   // фон кнопки
#define UI_COL_BORDER      UI_RGB565(0x2E, 0x3A, 0x50)   // рамки, разделители
#define UI_COL_HEADER      UI_RGB565(0x14, 0x19, 0x26)   // шапка и статус-бар
#define UI_COL_TRACK       UI_RGB565(0x10, 0x15, 0x1F)   // дорожка прогресса
#define UI_COL_ACCENT      UI_RGB565(0x38, 0xBD, 0xF8)   // акцент (голубой)
#define UI_COL_GREEN       UI_RGB565(0x4A, 0xDE, 0x80)   // успех/работает
#define UI_COL_RED         UI_RGB565(0xF8, 0x71, 0x71)   // ошибка/опасность
#define UI_COL_AMBER       UI_RGB565(0xFB, 0xBF, 0x24)   // предупреждение
#define UI_COL_TEXT        UI_RGB565(0xE8, 0xED, 0xF7)   // основной текст
#define UI_COL_TEXT_DIM    UI_RGB565(0x93, 0xA1, 0xB8)   // вторичный текст
#define UI_COL_TEXT_DARK   UI_RGB565(0x0B, 0x12, 0x20)   // текст на акценте
#define UI_COL_DOT_OFF     UI_RGB565(0x3A, 0x44, 0x58)   // погашенный индикатор

// ----------------------------------------------------------------------------
// Прямоугольник — базовый кирпич компоновки (панели, кнопки, строки)
// ----------------------------------------------------------------------------
typedef struct {
    int x;      // левый край, пикселей
    int y;      // верхний край, пикселей
    int w;      // ширина, пикселей
    int h;      // высота, пикселей
} ui_rect_t;

// ----------------------------------------------------------------------------
// Шрифт: набор глифов, конвертированных из готового TTF-шрифта DejaVu Sans
// (файлы ui_font_*.c генерируются скриптом tools/make_font.py)
// ----------------------------------------------------------------------------

// Описание одного глифа (одного символа шрифта)
typedef struct {
    uint16_t cp;        // кодовая точка Unicode (0x0410 = 'А' кириллица)
    uint8_t  w;         // ширина растра глифа, пикселей
    uint8_t  h;         // высота растра глифа, пикселей
    uint8_t  advance;   // шаг пера: на сколько пикселей сдвинуться вправо
    int8_t   x0;        // сдвиг растра влево от точки рисования (левое поле)
    int8_t   y0;        // сдвиг растра вниз от верхней линии строки
    uint16_t offset;    // смещение растра глифа в общем массиве битmaps
} ui_glyph_t;

// Описание шрифта целиком
typedef struct {
    uint8_t             line_height;  // высота строки (ascent+descent), пикселей
    uint8_t             ascent;       // высота от базовой линии до верха строки
    uint16_t            glyph_count;  // число глифов
    const ui_glyph_t   *glyphs;       // таблица глифов (отсортирована по cp)
    const uint8_t      *bitmap;       // общий массив растров (1 бит на пиксель)
} ui_font_t;

// Готовые шрифты проекта (сгенерированы из DejaVu Sans, есть кириллица):
//   ui_font_sans16  — обычный текст панелей, подписи, статус-бар;
//   ui_font_sans24b — заголовки панелей, кнопки, крупные значения (Bold);
//   ui_font_sans40b — крупный заголовок сплэш-экрана (Bold).
extern const ui_font_t ui_font_sans16;
extern const ui_font_t ui_font_sans24b;
extern const ui_font_t ui_font_sans40b;

// ----------------------------------------------------------------------------
// Базовые примитивы рисования (все с защитой от выхода за границы экрана)
// ----------------------------------------------------------------------------
void ui_fill_rect(uint16_t *fb, ui_rect_t r, uint16_t color);   // заливка
void ui_frame_rect(uint16_t *fb, ui_rect_t r, uint16_t color);  // рамка 1 px
void ui_hline(uint16_t *fb, int x, int y, int len, uint16_t color); // гор. линия
void ui_vline(uint16_t *fb, int x, int y, int len, uint16_t color); // верт. линия

// ----------------------------------------------------------------------------
// Текст (UTF-8 строки, кириллица поддерживается шрифтами)
// ----------------------------------------------------------------------------

// Декодирование одной UTF-8 последовательности: cp — код символа,
// возвращаемое значение — сколько байт строка занимает (1..4)
int ui_utf8_decode(const char *s, uint32_t *cp);

// Один символ; возвращает шаг пера (на сколько сдвинуть x для следующего)
int ui_draw_char(uint16_t *fb, int x, int y, uint32_t cp,
                 const ui_font_t *font, uint16_t color);

// Строка от точки (x, y); возвращает x правее последнего символа
int ui_draw_text(uint16_t *fb, int x, int y, const char *utf8,
                 const ui_font_t *font, uint16_t color);

// Ширина строки в пикселях (сумма шагов пера) — для центрирования/разметки
int ui_text_width(const char *utf8, const ui_font_t *font);

// Строка, центрированная внутри прямоугольника (по горизонтали и вертикали)
void ui_draw_text_centered(uint16_t *fb, ui_rect_t r, const char *utf8,
                           const ui_font_t *font, uint16_t color);

// Пара "ключ: значение" — подпись приглушённым цветом, значение основным.
// value_col — ширина колонки подписи (значение рисуется в x + value_col)
void ui_kv_line(uint16_t *fb, int x, int y, const char *key, const char *value,
                const ui_font_t *font, int value_col);

// ----------------------------------------------------------------------------
// Готовые виджеты (компоновочные элементы UI)
// ----------------------------------------------------------------------------

// Панель: заливка + рамка + заголовок акцентным цветом + разделительная линия.
// Если title == NULL — рисуется только рамка без заголовка.
void ui_panel_draw(uint16_t *fb, ui_rect_t r, const char *title,
                   const ui_font_t *title_font);

// Стили кнопок
typedef enum {
    UI_BTN_NORMAL = 0,  // тёмная кнопка со светлой рамкой
    UI_BTN_ACCENT,      // акцентная (голубая заливка, тёмный текст) — "главная"
    UI_BTN_DANGER,      // контурная красная — "осторожно/сброс"
} ui_btn_style_t;

// Кнопка с подписью по центру
void ui_button_draw(uint16_t *fb, ui_rect_t r, const char *label,
                    ui_btn_style_t style);

// Полоса прогресса: 0..100 %. fill_color — цвет заполнения
void ui_progress_draw(uint16_t *fb, ui_rect_t r, int percent, uint16_t fill_color);

#endif // UI_H
