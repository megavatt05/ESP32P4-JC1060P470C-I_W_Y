// ============================================================================
//  ui_demo.h — демо-экран 1024x600: пример построения UI на примитивах ui.h
//  Проект: jd9165_hello_display (ESP32-P4, панель JD9165, Guition JC1060P470C)
// ----------------------------------------------------------------------------
//  Два вызова образуют весь "фреймворк" приложения:
//    ui_demo_draw(fb)        — один раз рисует весь экран (статика);
//    ui_demo_tick(fb, ...)   — периодически перерисовывает ТОЛЬКО динамику
//                              (uptime, прогресс, индикаторы), а не весь кадр.
// ============================================================================

#ifndef UI_DEMO_H
#define UI_DEMO_H

#include <stdint.h>

// Полная отрисовка демо-экрана: шапка, 3 панели, панель прогресса,
// ряд кнопок, статус-бар. Дорогая операция (~один раз при старте).
void ui_demo_draw(uint16_t *fb);

// "Тик" динамики: обновляет секунды работы, полосу прогресса и индикаторы.
// Вызывать периодически (например каждые 100 мс); параметры:
//   uptime_sec   — секунды с момента старта (для счётчика);
//   progress_pct — процент 0..100 для полосы прогресса.
void ui_demo_tick(uint16_t *fb, int uptime_sec, int progress_pct);

// Сплэш-экран (показывается перед демо-UI): крупное приветствие и
// сведения о плате. Рисуется один раз.
void ui_splash_draw(uint16_t *fb);

#endif // UI_DEMO_H
